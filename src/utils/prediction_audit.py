"""Recompute image-level results and check declared exposure, without training."""
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd

from src.data.full_isic import CLASS_NAMES
from src.utils.feature_training import score_predictions


def digest(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def manifest(path):
    frame = pd.read_csv(path, dtype=str, keep_default_na=False)
    required = {'image_id', 'label'}
    if not required <= set(frame):
        raise ValueError(f'{path}: requires image_id and label')
    if frame.empty or frame.image_id.str.strip().eq('').any() or not frame.image_id.is_unique:
        raise ValueError(f'{path}: image IDs must be nonempty and unique')
    if not frame.label.isin(CLASS_NAMES).all():
        raise ValueError(f'{path}: unknown ground-truth label')
    return frame


def audit_predictions(predictions, truth, exposure, reported_metrics=None, split=None,
                      require_disjoint=False):
    """Exposure must include every train/tune/selection cohort in the lineage.

    Passing overlap checks cannot prove completeness of that declaration, unseen
    patients, or that these probabilities were generated by a particular model.
    """
    cohort = manifest(truth)
    seen = manifest(exposure)
    table = pd.read_csv(predictions, dtype={'image_id': str}, keep_default_na=False)
    if 'image_id' not in table or not table.image_id.is_unique:
        raise ValueError('Predictions require unique image_id values')
    if set(table.image_id) != set(cohort.image_id):
        raise ValueError('Prediction IDs must exactly match the ground-truth cohort')
    table = table.set_index('image_id').loc[cohort.image_id]
    if 'true_label' in table and not np.array_equal(table.true_label.to_numpy(), cohort.label.to_numpy()):
        raise ValueError('Prediction labels disagree with independent ground truth')
    columns = CLASS_NAMES if set(CLASS_NAMES) <= set(table) else ['score_' + c for c in CLASS_NAMES]
    if not set(columns) <= set(table):
        raise ValueError('Predictions require seven class-probability columns')
    probabilities = table[columns].to_numpy(dtype=float)
    y = cohort.label.map(dict(zip(CLASS_NAMES, range(7)))).to_numpy()
    metrics = score_predictions(y, probabilities)
    overlaps = {}
    completeness = {}
    for key in ['image_id', 'image_sha256', 'lesion_id', 'patient_id']:
        available = key in cohort and key in seen
        complete = available and all(frame[key].str.strip().ne('').all() for frame in [cohort, seen])
        if complete and key == 'image_sha256':
            complete = all(frame[key].str.fullmatch('[0-9a-fA-F]{64}').all() for frame in [cohort, seen])
        completeness[key] = bool(complete)
        if available:
            left = cohort[key].str.strip()
            right = seen[key].str.strip()
            if key == 'image_sha256':
                left, right = left.str.lower(), right.str.lower()
            overlaps[key] = sorted((set(left) & set(right)) - {''})
        else:
            overlaps[key] = None
    # IDs must be globally reconciled across releases. Missing evidence fails closed.
    disjoint = all(completeness[k] for k in ['image_id', 'image_sha256', 'lesion_id']) and not any(overlaps.values())
    if require_disjoint and not disjoint:
        raise ValueError('Disjoint evaluation rejected: overlapping or missing image/hash/lesion evidence')
    if reported_metrics is not None:
        reported = json.loads(Path(reported_metrics).read_text(encoding='utf-8'))
        if split:
            reported = reported[split]
        for key in ['images', 'accuracy', 'balanced_accuracy', 'macro_f1', 'weighted_f1', 'macro_f05']:
            if key not in reported or not np.isclose(float(reported[key]), metrics[key], rtol=0, atol=1e-10):
                raise ValueError(f'Reported metric disagrees with predictions: {key}')
    return {'metrics': metrics, 'overlaps': overlaps, 'identity_evidence_complete': completeness,
            'declared_image_and_lesion_disjoint': bool(disjoint),
            'independent_generalization_established': False,
            'limitations': 'Checks declared exposure only. Requires independently verified lineage, globally '
                          'reconciled identities and a model frozen before blind evaluation. '
                          'Patient independence is unverified unless complete patient IDs are supplied.',
            'input_sha256': {str(path): digest(path) for path in
                             [predictions, truth, exposure] + ([reported_metrics] if reported_metrics else [])}}
